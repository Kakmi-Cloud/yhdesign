/** 只按 id 取资料；缺资料返回 null，绝不静默回退到别的项目内容。 */
export function getDossier(id) {
  return Object.prototype.hasOwnProperty.call(DOSSIERS, String(id)) ? DOSSIERS[String(id)] : null
}

/** 首页 / 列表用的短状态标签 */
export function statusLabel(id) {
  const d = getDossier(id)
  return d ? d.badge : '设计资料'
}

export default DOSSIERS
